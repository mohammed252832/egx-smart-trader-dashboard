from __future__ import annotations

from pathlib import Path
from typing import Any

from .config import Config
from .model import TrainedModel

DEFAULT_REPORT_PATH = Path(__file__).resolve().parent.parent / "docs" / "MODEL_REPORT.md"


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def build_report(model: TrainedModel, config: Config) -> str:
    rules = config.signals.signals
    risk = config.signals.risk
    weights = config.signals.score
    metrics = model.metrics or {}
    signals = metrics.get("signals") or {}

    lines = [
        "# Model and Signal Report",
        "",
        "Generated by the analysis pipeline. Metrics below come from the most recent run; "
        "a dash means the run did not have enough data to compute that value.",
        "",
        "## Methodology",
        "",
        f"- Model version: `{model.version}`",
        f"- Label: forward return over `{config.horizon_days}` sessions is at least "
        f"`{config.target_pct:.2f}%`.",
        f"- Split: chronological `{config.signals.model.train_fraction:.0%}` train / validation, "
        f"with a `{max(config.signals.model.purge_sessions, config.horizon_days)}`-session purge "
        "on both sides of the boundary (the larger of the configured purge and the label "
        "horizon) so forward windows never overlap the two sets.",
        "- Features are computed only from past and current bars; no random shuffling is used.",
        f"- Training rows: `{model.train_rows}`; validation accuracy: "
        f"`{_fmt(model.validation_accuracy)}`.",
        "",
        "## Validation metrics",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        f"| Accuracy | {_fmt(metrics.get('accuracy'))} |",
        f"| Precision (probability >= 0.5) | {_fmt(metrics.get('precision'))} |",
        f"| Recall (probability >= 0.5) | {_fmt(metrics.get('recall'))} |",
        f"| Buy hit rate | {_fmt(signals.get('buy_hit_rate'))} |",
        f"| Buy precision | {_fmt(signals.get('buy_precision'))} |",
        f"| Buy recall | {_fmt(signals.get('buy_recall'))} |",
        f"| Average forward return on buy signals (%) | {_fmt(signals.get('average_forward_return_buy'))} |",
        "",
        "## Signal counts on validation",
        "",
    ]
    counts = signals.get("counts") or {}
    if counts:
        lines += ["| Signal | Rows |", "| --- | ---: |"]
        lines += [f"| {name} | {count} |" for name, count in sorted(counts.items())]
    else:
        lines.append("No validation signal counts available.")

    lines += [
        "",
        "## Strength score",
        "",
        "The strength score is a transparent weighted sum, not a model probability:",
        "",
        f"- Probability: `{weights.probability}`",
        f"- Reward/risk: `{weights.reward_risk}`",
        f"- Momentum: `{weights.momentum}`",
        f"- Volume confirmation: `{weights.volume}`",
        "",
        "Each component is normalised to 0–1, multiplied by its weight, divided by the total "
        "weight, and shown as 0–100. Reward/risk is capped at "
        f"`{risk.max_reward_risk:.2f}` for scoring.",
        "",
        "## Risk rules",
        "",
        f"- Target: `max({risk.min_target_pct}%, {risk.target_atr_multiplier} × ATR%)`, "
        f"capped at `{risk.max_target_pct}%` and `{risk.max_upside_pct}%` upside.",
        f"- Stop: `clamp({risk.stop_atr_multiplier} × ATR%, {risk.min_stop_pct}%, "
        f"{risk.max_stop_pct}%)`, widened to the recent support level when configured.",
        f"- EGX daily limit: `{risk.price_limit_pct}%` with a "
        f"`{risk.limit_buffer_pct}%` safety buffer; prices are rounded to configured tick sizes.",
        "",
        "## Signal thresholds",
        "",
        f"- Strong buy: probability >= `{rules.strong_buy_probability}`, "
        f"score >= `{rules.strong_buy_score}`, reward/risk >= `{rules.min_reward_risk}`.",
        f"- Buy: probability >= `{rules.buy_probability}` and "
        f"reward/risk >= `{rules.min_reward_risk}`.",
        f"- Avoid: probability < `{rules.avoid_probability}` or "
        f"reward/risk < `{rules.min_reward_risk}`.",
        "- Watch: everything else.",
        "",
        "All thresholds live in `engine/config/signals.json` and can be changed without code edits.",
        "",
    ]
    return "\n".join(lines)


def write_model_report(model: TrainedModel, config: Config, path: Path = DEFAULT_REPORT_PATH) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build_report(model, config), encoding="utf-8")
    return target
